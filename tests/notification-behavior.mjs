import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('src/main.js','utf8');
const fn=source.slice(source.indexOf('async function sendSystemNotification('),source.indexOf('function promptPushPermissionModal('));
const notices=[];
function Notification(title,options){notices.push({title,options});}
Notification.permission='granted';
const context=vm.createContext({NATIVE:false,Notification,navigator:{},console,Date});
vm.runInContext(fn,context);
const privateNotice={title:'Private child',message:'Private health and pickup code',kind:'urgent_call'};
await context.sendSystemNotification(privateNotice);
assert.equal(notices.length,0,'Production updates must not duplicate server push');
await context.sendSystemNotification({...privateNotice,isTest:true});
assert.equal(notices.length,1);
assert(!JSON.stringify(notices).includes('Private'));
const handlers={},displayed=[],opened=[];let pending;
const worker=vm.createContext({self:{addEventListener:(name,cb)=>handlers[name]=cb,location:{origin:'https://example.test'},clients:{matchAll:async()=>[],openWindow:async url=>opened.push(url)},registration:{getNotifications:async()=>[],showNotification:async(title,options)=>displayed.push({title,options})}},Date,URL,console});
vm.runInContext(fs.readFileSync('public/sw.js','utf8'),worker);
handlers.push({data:{json:()=>({urgent:true,url:'/kids#notifications',child_name:'Private child',reason:'Private health',claim_code:'PRIVATE'})},waitUntil:p=>pending=p});await pending;
assert(!displayed[0].title.includes('Private'));
assert(!displayed[0].options.body.includes('Private'));
handlers.notificationclick({action:'on_my_way',notification:{data:displayed[0].options.data,close(){}},waitUntil:p=>pending=p});await pending;
assert.deepEqual(opened,['https://example.test/kids#notifications']);
assert.equal(displayed.length,1,'Opening the app must not acknowledge a pickup request');
handlers.notificationclick({notification:{data:{url:'https://elsewhere.test/private'},close(){}},waitUntil:p=>pending=p});await pending;
assert.equal(opened[1],'https://example.test/membro');
console.log('Notification checks: no duplicate, private preview, contextual opening and same-origin routing passed');
