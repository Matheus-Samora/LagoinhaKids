CREATE OR REPLACE FUNCTION kids_notification_queue() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO outbox(notification_id) VALUES(NEW.id) ON CONFLICT DO NOTHING;
 IF NEW.child_id IS NOT NULL AND NEW.user_id=(SELECT parent_id FROM children WHERE id=NEW.child_id) THEN
  INSERT INTO notifications(user_id,child_id,kind,title,message,sender,created_at)
  SELECT f.user_id,NEW.child_id,NEW.kind,NEW.title,NEW.message,NEW.sender,NEW.created_at
  FROM family_links f JOIN users u ON u.id=f.user_id WHERE f.child_id=NEW.child_id AND f.active=1 AND u.active=1 AND f.user_id!=NEW.user_id;
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS kids_notification_queue ON notifications;
CREATE TRIGGER kids_notification_queue AFTER INSERT ON notifications FOR EACH ROW EXECUTE FUNCTION kids_notification_queue();
